def read_toml(path: Path) -> dict:
    if tomllib is None:
        return {}
    try:
        with open(path, "rb") as fh:
            return tomllib.load(fh)
    except Exception:
        return {}


def parse_cargo(path: Path) -> dict:
    data = read_toml(path)
    deps = set()
    for key in ("dependencies", "dev-dependencies", "build-dependencies"):
        deps.update((data.get(key) or {}).keys())
    ws = data.get("workspace") or {}
    deps.update((ws.get("dependencies") or {}).keys())
    for target in (data.get("target") or {}).values():
        if isinstance(target, dict):
            deps.update((target.get("dependencies") or {}).keys())
    if not data:  # crude fallback
        try:
            text = path.read_text(errors="replace")
            deps.update(re.findall(r"^\s*([A-Za-z0-9_-]+)\s*=", text, re.M))
        except OSError:
            pass
    pkg = data.get("package") or {}
    return {
        "kind": "cargo",
        "name": pkg.get("name"),
        "edition": pkg.get("edition"),
        "rust_version": pkg.get("rust-version"),
        "is_workspace_root": bool(ws),
        "workspace_members": ws.get("members", []),
        "has_lints_table": "lints" in data or "lints" in ws,
        "dependencies": sorted(deps),
    }


def parse_package_json(path: Path) -> dict:
    try:
        data = json.loads(path.read_text(errors="replace"))
    except Exception:
        data = {}
    deps = {}
    for key in ("dependencies", "devDependencies", "peerDependencies"):
        deps.update(data.get(key) or {})
    return {
        "kind": "npm",
        "name": data.get("name"),
        "scripts": data.get("scripts", {}),
        "package_manager": data.get("packageManager"),
        "engines": data.get("engines"),
        "workspaces": data.get("workspaces"),
        "type": data.get("type"),
        "dependencies": sorted((data.get("dependencies") or {}).keys()),
        "dev_dependencies": sorted((data.get("devDependencies") or {}).keys()),
        "versions": {k: deps[k] for k in deps if k in
                     {"next", "react", "typescript", "vitest", "jest", "@playwright/test", "eslint"}},
    }


# --------------------------------------------------------------------------------------------
# Reference resolution
# --------------------------------------------------------------------------------------------

def slug(dep: str) -> str:
    if dep in DEP_ALIASES:
        return DEP_ALIASES[dep]
    return dep.lstrip("@").replace("/", "-").lower()


def references_for(langs: set[str], deps: set[str]) -> tuple[list[str], list[str], list[str]]:
    """Return (reference paths, matched stacks, notable deps without a reference)."""
    refs: list[str] = []
    stacks: list[str] = []
    missing: list[str] = []
    for lang in sorted(langs):
        ref_lang = LANG_REFERENCE_DIR.get(lang, lang)
        index = REF_DIR / ref_lang / "index.md"
        if index.exists():
            rel = str(index.relative_to(SKILL_DIR))
            if rel not in refs:
                refs.append(rel)
        for dep in sorted(deps):
            s = slug(dep)
            found = False
            for kind in ("framework", "lib"):
                f = REF_DIR / ref_lang / kind / f"{s}.md"
                if f.exists():
                    rel = str(f.relative_to(SKILL_DIR))
                    if rel not in refs:
                        refs.append(rel)
                        stacks.append(f"{kind}:{s}")
                    found = True
            if not found and dep in NOTABLE_DEPS.get(ref_lang, []):
                missing.append(dep)
    return refs, stacks, sorted(set(missing))


# --------------------------------------------------------------------------------------------
# Partitioning
# --------------------------------------------------------------------------------------------

def build_units(files: list[dict], target: int) -> list[dict]:
    """Recursively split directories until each unit is <= target LOC (or a single file)."""
    tree: dict = {"files": [], "dirs": {}}
    for f in files:
        node = tree
        parts = f["path"].split("/")
        for part in parts[:-1]:
            node = node["dirs"].setdefault(part, {"files": [], "dirs": {}})
        node["files"].append(f)

    def loc_of(node) -> int:
        return sum(x["loc"] for x in node["files"]) + sum(loc_of(n) for n in node["dirs"].values())

    def all_files(node) -> list[dict]:
        out = list(node["files"])
        for n in node["dirs"].values():
            out.extend(all_files(n))
        return out

    units: list[dict] = []

    def walk(node, prefix: str):
        total = loc_of(node)
        if total <= target or (not node["dirs"] and len(node["files"]) <= 1):
            fs = all_files(node)
            if fs:
                units.append({"paths": [prefix or "."], "files": fs, "loc": total})
            return
        loose = node["files"]
        if loose:
            loose_loc = sum(x["loc"] for x in loose)
            if loose_loc <= target:
                units.append({"paths": [x["path"] for x in loose], "files": loose, "loc": loose_loc})
            else:
                for x in sorted(loose, key=lambda x: x["path"]):
                    units.append({"paths": [x["path"]], "files": [x], "loc": x["loc"]})
        for name in sorted(node["dirs"]):
            walk(node["dirs"][name], f"{prefix}/{name}" if prefix else name)

    walk(tree, "")
    return units


def pack(units: list[dict], target: int) -> list[dict]:
    parts: list[dict] = []
    cur: dict | None = None
    for u in units:
        if cur is None or (cur["loc"] + u["loc"] > target and cur["loc"] > 0) \
                or (u["package"] != cur["packages"][-1] and cur["loc"] >= target // 2):
            cur = {"paths": [], "files": [], "loc": 0, "packages": [u["package"]]}
            parts.append(cur)
        cur["paths"].extend(u["paths"])
        cur["files"].extend(u["files"])
        cur["loc"] += u["loc"]
        if u["package"] not in cur["packages"]:
            cur["packages"].append(u["package"])
    return parts


