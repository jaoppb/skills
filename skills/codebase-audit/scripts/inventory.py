# --------------------------------------------------------------------------------------------
# File listing
# --------------------------------------------------------------------------------------------

def run(cmd: list[str], cwd: Path) -> str | None:
    try:
        return subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, timeout=60,
                              check=True).stdout
    except Exception:
        return None


def list_files(root: Path) -> list[str]:
    """Repo-relative POSIX paths. Uses git (respects .gitignore) when available."""
    out = run(["git", "ls-files", "--cached", "--others", "--exclude-standard"], root)
    if out:
        files = [f for f in out.splitlines() if f]
        return [f for f in files if not any(part in EXCLUDE_DIRS for part in f.split("/"))
                and (root / f).is_file()]
    files = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in EXCLUDE_DIRS]
        for name in filenames:
            rel = os.path.relpath(os.path.join(dirpath, name), root)
            files.append(rel.replace(os.sep, "/"))
    return files


def match_any(path: str, patterns: list[str]) -> bool:
    p = "/" + path
    return any(fnmatch.fnmatch(p, "*/" + pat.lstrip("*/")) or fnmatch.fnmatch(p, pat)
               or fnmatch.fnmatch(path, pat) for pat in patterns)


def count_loc(path: Path) -> tuple[int, bool, bool]:
    """Return (non-blank lines, looks_generated, has_inline_rust_tests)."""
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            text = fh.read(2_000_000)
    except OSError:
        return 0, False, False
    loc = sum(1 for line in text.splitlines() if line.strip())
    head = text[:1500]
    generated = bool(GENERATED_MARKERS.search(head))
    inline_tests = "#[cfg(test)]" in text
    return loc, generated, inline_tests


