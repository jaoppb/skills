#!/usr/bin/env python3
"""Inventory a repository for the codebase-audit skill.

Detects languages, packages, frameworks/libraries (and which reference files apply), test layout,
tooling/CI/docs configuration, largest files, churn hotspots, and proposes partitions sized for one
review subagent each.

Usage:
    python3 inventory.py <repo-root> [--out inventory.json] [--target-loc 6000]

Only the standard library is used. Output is JSON; a short human summary is printed to stdout.
"""
