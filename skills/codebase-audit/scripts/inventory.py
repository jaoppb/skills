# Main
# --------------------------------------------------------------------------------------------

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("root")
    ap.add_argument("--out", default=None, help="write JSON here (default: stdout only summary)")
    ap.add_argument("--target-loc", type=int, default=6000, help="approx LOC per partition")
    args = ap.parse_args()

    root = Path(args.root).resolve()
    if not root.is_dir():
        print(f"not a directory: {root}", file=sys.stderr)
        return 2

    paths = list_files(root)

    # Manifests / packages
    packages: dict[str, dict] = {}
    for p in paths:
        name = p.rsplit("/", 1)[-1]
        d = p.rsplit("/", 1)[0] if "/" in p else "."
        if name == "Cargo.toml":
            packages.setdefault(d, {"dir": d, "manifests": []})["manifests"].append(
                {"path": p, **parse_cargo(root / p)})
        elif name == "package.json":
            packages.setdefault(d, {"dir": d, "manifests": []})["manifests"].append(
                {"path": p, **parse_package_json(root / p)})
    if "." not in packages:
        packages["."] = {"dir": ".", "manifests": []}

    def owning_package(path: str) -> str:
        best = "."
        for d in packages:
            if d != "." and (path == d or path.startswith(d + "/")) and len(d) > len(best):
                best = d
        return best

    # Files
    code_files: list[dict] = []
    lang_loc: Counter = Counter()
    lang_files: Counter = Counter()
    test_counts = Counter()
    generated: list[str] = []
    for p in paths:
        ext = os.path.splitext(p)[1].lower()
        lang = LANG_BY_EXT.get(ext)
        if not lang:
            continue
        loc, gen_marker, inline_tests = count_loc(root / p)
        is_generated = gen_marker or match_any(p, GENERATED_PATTERNS)
        is_test = match_any(p, TEST_PATTERNS)
        kind = "source"
        if is_test:
            kind = "e2e" if match_any(p, E2E_PATTERNS) else (
                "integration" if match_any(p, INTEGRATION_PATTERNS)
                or (lang == "rust" and re.match(r"(.*/)?tests/", p)) else "unit")
            test_counts[kind] += 1
        if lang == "rust" and inline_tests and not is_test:
            test_counts["rust_inline_test_modules"] += 1
        if is_generated:
            generated.append(p)
        f = {"path": p, "lang": lang, "loc": loc, "kind": kind, "generated": is_generated,
             "package": owning_package(p), "inline_tests": inline_tests}
        if not is_generated:
            code_files.append(f)
            lang_loc[lang] += loc
            lang_files[lang] += 1

    # Package stacks + references
    pkg_summ = []
    for d, pkg in sorted(packages.items()):
        deps: set[str] = set()
        for m in pkg["manifests"]:
            deps.update(m.get("dependencies", []))
            deps.update(m.get("dev_dependencies", []))
        langs = {f["lang"] for f in code_files if f["package"] == d}
        if any(m["kind"] == "npm" for m in pkg["manifests"]) and \
                ("typescript" in deps or (root / d / "tsconfig.json").exists()):
            langs.add("typescript")
        langs = {l for l in langs if l not in {"sql", "shell"}}
        refs, stacks, missing = references_for(langs, deps)
        pkg["langs"] = sorted(langs)
        pkg["references"] = refs
        pkg["stacks"] = stacks
        pkg["notable_without_reference"] = missing
        src = [f for f in code_files if f["package"] == d]
        pkg_summ.append({
            "dir": d,
            "names": [m.get("name") for m in pkg["manifests"] if m.get("name")],
            "manifests": [m["path"] for m in pkg["manifests"]],
            "langs": pkg["langs"],
            "stacks": stacks,
            "references": refs,
            "notable_without_reference": missing,
            "loc": sum(f["loc"] for f in src),
            "source_files": sum(1 for f in src if f["kind"] == "source"),
            "test_files": sum(1 for f in src if f["kind"] != "source"),
            "scripts": next((m.get("scripts") for m in pkg["manifests"] if m["kind"] == "npm"), None),
            "versions": next((m.get("versions") for m in pkg["manifests"] if m["kind"] == "npm"), None),
            "cargo": next(({k: m.get(k) for k in ("edition", "rust_version", "is_workspace_root",
                                                   "has_lints_table")}
                           for m in pkg["manifests"] if m["kind"] == "cargo"), None),
        })
    # drop empty root pseudo-package
    pkg_summ = [p for p in pkg_summ if p["loc"] or p["manifests"]]

    # Config presence
    configs = {}
    for key, patterns in CONFIG_CHECKS.items():
        hits = [p for p in paths if match_any(p, patterns) and p.count("/") <= 3]
        configs[key] = sorted(hits)[:25]

    # Largest files / git info
    largest = sorted(code_files, key=lambda f: f["loc"], reverse=True)[:20]
    git = {"sha": None, "churn_top": []}
    sha = run(["git", "rev-parse", "--short", "HEAD"], root)
    if sha:
        git["sha"] = sha.strip()
        log = run(["git", "log", "--since=12 months ago", "--format=", "--name-only"], root)
        if log:
            churn = Counter(l for l in log.splitlines() if l and LANG_BY_EXT.get(
                os.path.splitext(l)[1].lower()))
            git["churn_top"] = [{"path": p, "commits": c} for p, c in churn.most_common(20)]

    # Partitions
    units = build_units(code_files, args.target_loc)
    for u in units:
        u["package"] = u["files"][0]["package"]
    units.sort(key=lambda u: (u["package"], u["paths"][0]))
    parts = pack(units, args.target_loc)
    partitions = []
    for i, part in enumerate(parts, 1):
        langs = {f["lang"] for f in part["files"]}
        refs = ["references/generic-practices.md", "references/code-smells.md"]
        for pdir in part["packages"]:
            for r in packages.get(pdir, {}).get("references", []):
                if r not in refs:
                    refs.append(r)
        partitions.append({
            "id": f"module-{i}",
            "paths": part["paths"],
            "packages": part["packages"],
            "loc": part["loc"],
            "files": len(part["files"]),
            "test_files": sum(1 for f in part["files"] if f["kind"] != "source"),
            "langs": sorted(langs),
            "references": refs,
        })

    total_loc = sum(lang_loc.values())
    src_files = sum(1 for f in code_files if f["kind"] == "source")
    tst_files = sum(1 for f in code_files if f["kind"] != "source")
    unsupported = sorted({l for l in lang_loc if l not in {"sql", "shell"}
                          and not (REF_DIR / LANG_REFERENCE_DIR.get(l, l) / "index.md").exists()})

    result = {
        "repo_root": str(root),
        "repo_name": root.name,
        "date": date.today().isoformat(),
        "git": git,
        "totals": {"loc": total_loc, "code_files": len(code_files), "source_files": src_files,
                   "test_files": tst_files,
                   "test_to_source_file_ratio": round(tst_files / src_files, 2) if src_files else None,
                   "generated_files_excluded": len(generated)},
        "languages": [{"lang": l, "loc": lang_loc[l], "files": lang_files[l]}
                      for l, _ in lang_loc.most_common()],
        "languages_without_reference": unsupported,
        "tests": dict(test_counts),
        "packages": pkg_summ,
        "configs": configs,
        "missing_configs": sorted(k for k, v in configs.items()
                                  if not v and k not in {"env_committed", "adr", "monorepo"}),
        "largest_files": [{"path": f["path"], "loc": f["loc"]} for f in largest],
        "generated_files_sample": generated[:30],
        "partitions": partitions,
        "partition_target_loc": args.target_loc,
    }

    text = json.dumps(result, indent=2)
    if args.out:
        out = Path(args.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text)
    else:
        print(text)
        return 0

    # Short human summary
    print(f"repo: {root.name}  sha: {git['sha']}  loc: {total_loc}  "
          f"files: {src_files} source / {tst_files} test")
    print("languages: " + ", ".join(f"{x['lang']}={x['loc']}" for x in result["languages"][:6]))
    for p in pkg_summ:
        print(f"package {p['dir']}: {','.join(p['langs']) or '-'} "
              f"stacks={','.join(p['stacks']) or '-'} loc={p['loc']}"
              + (f" no-ref={','.join(p['notable_without_reference'])}"
                 if p['notable_without_reference'] else ""))
    print(f"tests: {dict(test_counts)}")
    print(f"missing configs: {', '.join(result['missing_configs']) or 'none'}")
    if configs.get("env_committed"):
        print(f"WARNING committed env files: {', '.join(configs['env_committed'])}")
    if unsupported:
        print(f"languages without a dedicated reference: {', '.join(unsupported)}")
    print(f"partitions: {len(partitions)} (target {args.target_loc} LOC)")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
